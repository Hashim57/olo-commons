#!/usr/bin/env python3
"""Write docs/ZEUS_SCORECARD.md from measured numbers only.

  python3 zeus/cloud/scorecard.py            # the version in zeus/BEST.json
  python3 zeus/cloud/scorecard.py v7         # a given version

Three kinds of number, kept apart on purpose: the frozen rule-made eval split
(saturated by a 7B model, so it no longer separates versions), the held-out sets
nobody trained on (VitaminC dev, LLM-AggreFact), and the served copy on Cloudflare.
Published checkers are listed with the year of their figure so the comparison is
fair: LLM-AggreFact is two-label, so Zeus's contradicted and not_covered both count
as unsupported there. Nothing here is estimated; a missing file prints "not measured".
"""
import json
import os
import sys
from datetime import datetime, timezone

ZEUS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(os.path.dirname(ZEUS), "docs")

BASELINES = [
    ("Bespoke-MiniCheck-7B (non-commercial licence)", "7B", 77.4, "2024", "https://bespokelabs.ai/bespoke-minicheck"),
    ("FactCG-DeBERTa", "0.4B", 77.2, "2025", "https://arxiv.org/pdf/2501.17144"),
    ("gpt-4-turbo (prompted)", "large", 76.2, "2025", "https://arxiv.org/pdf/2501.14883"),
    ("GPT-4o (prompted)", "large", 75.9, "2025", "https://arxiv.org/pdf/2501.17144"),
    ("MiniCheck-FT5", "Flan-T5-Large", 75.5, "2024", "https://arxiv.org/pdf/2501.17144"),
    ("Vectara HHEM-2.1", "not stated", 71.8, "2024", "https://bespokelabs.ai/bespoke-minicheck"),
]


def load(path):
    try:
        return json.load(open(path, encoding="utf-8"))
    except (OSError, ValueError):
        return None


def pct(x):
    return "not measured" if x is None else f"{100 * x:.1f}%" if isinstance(x, float) and x <= 1 else str(x)


def main():
    best = load(os.path.join(ZEUS, "BEST.json")) or {}
    v = sys.argv[1] if len(sys.argv) > 1 else best.get("version")
    if not v:
        sys.exit("no version")
    out = os.path.join(ZEUS, "out", f"zeus-{v}")
    ev, ext, cf, tr = load(os.path.join(out, "eval.json")) or {}, load(os.path.join(out, "eval-external.json")) or {}, load(os.path.join(out, "eval-cloudflare.json")) or {}, load(os.path.join(out, "train_summary.json")) or {}
    vit, agg, ev2 = ext.get("vitaminc_dev") or {}, ext.get("llm_aggrefact") or {}, ext.get("eval_v2") or {}
    L = []
    L.append(f"# Zeus scorecard: {v}\n")
    L.append(f"Measured {datetime.now(timezone.utc).strftime('%Y-%m-%d')} UTC. Base {ev.get('base') or tr.get('base') or 'unknown'}, rank-{(tr.get('lora') or {}).get('r', '?')} LoRA, {tr.get('train_examples', '?')} training examples, {tr.get('minutes', '?')} minutes on {tr.get('gpu', 'a cloud GPU')}. Generated by zeus/cloud/scorecard.py from the files in zeus/out/zeus-{v}/; nothing here is estimated.\n")
    L.append("## Held-out sets (never trained on)\n")
    L.append("| Set | n | Label accuracy | Evidence hit | JSON valid | Binary balanced accuracy |\n| --- | --- | --- | --- | --- | --- |")
    if ev2.get("label_accuracy") is not None:
        L.append(f"| Commons eval v2 (frozen, harder: near misses, relation flips, true passage last) | {ev2.get('n')} | {pct(ev2.get('label_accuracy'))} | {pct(ev2.get('evidence_hit'))} | {pct(ev2.get('json_valid'))} | {pct(ev2.get('binary_balanced_accuracy'))} |")
    if vit:
        L.append(f"| VitaminC dev (human-written claims over Wikipedia revisions, three labels) | {vit.get('n')} | {pct(vit.get('label_accuracy'))} | {pct(vit.get('evidence_hit'))} | {pct(vit.get('json_valid'))} | {pct(vit.get('binary_balanced_accuracy'))} |")
    else:
        L.append("| VitaminC dev | not measured | | | | |")
    if agg.get("balanced_accuracy") is not None:
        L.append(f"| LLM-AggreFact test sample ({agg.get('sample')}) | {agg.get('n')} | two-label | | | {agg.get('balanced_accuracy')}% |")
    elif agg.get("error"):
        L.append(f"| LLM-AggreFact | not measured ({agg['error']}) | | | | |")
    else:
        L.append("| LLM-AggreFact | not measured | | | | |")
    L.append("")
    if ev2.get("by_kind"):
        L.append("Commons eval v2 by pattern (label accuracy):\n")
        L.append("| Pattern | n | Accuracy |\n| --- | --- | --- |")
        for k, d in ev2["by_kind"].items():
            L.append(f"| {k} | {d['n']} | {pct(d['accuracy'])} |")
        L.append("")
    if agg.get("per_dataset"):
        L.append("LLM-AggreFact by dataset (balanced accuracy, %):\n")
        L.append("| Dataset | n | Zeus |\n| --- | --- | --- |")
        for k, d in agg["per_dataset"].items():
            L.append(f"| {k} | {d['n']} | {d['balanced_accuracy']} |")
        L.append(f"\nDocuments cut to the prompt budget: {agg.get('truncated_docs', 0)} of {agg.get('n')}. Mapping: {agg.get('mapping')}. Benchmark: {agg.get('cite')}.\n")
    L.append("## Published checkers on LLM-AggreFact (balanced accuracy, full benchmark)\n")
    L.append("| Checker | Size | Score | Year | Source |\n| --- | --- | --- | --- | --- |")
    zeus_row = f"| **Zeus {v}** (sample above, not the full benchmark) | 7B LoRA | {agg.get('balanced_accuracy', 'not measured')} | {datetime.now(timezone.utc).year} | this file |"
    rows = [(b[2], f"| {b[0]} | {b[1]} | {b[2]} | {b[3]} | [{b[4].split('/')[2]}]({b[4]}) |") for b in BASELINES]
    if agg.get("balanced_accuracy") is not None:
        rows.append((agg["balanced_accuracy"], zeus_row))
    for _, r in sorted(rows, key=lambda x: -x[0]):
        L.append(r)
    if agg.get("balanced_accuracy") is None:
        L.append(zeus_row)
    L.append("\nA sample of a few hundred items has a few points of noise; a full-benchmark run is the fair comparison. Zeus's own case rests on what the two-label checkers lack: a third label (contradicted), a verbatim evidence quote and JSON output.\n")
    L.append("## Frozen eval split (rule-made, saturated)\n")
    L.append(f"n {ev.get('n')}, label accuracy {pct(ev.get('label_accuracy'))}, evidence hit {pct(ev.get('evidence_hit'))}, JSON valid {pct(ev.get('json_valid'))}, F1 supported {(ev.get('f1') or {}).get('supported')} / contradicted {(ev.get('f1') or {}).get('contradicted')} / not covered {(ev.get('f1') or {}).get('not_covered')}. This split is made by the same rules as the training data, so from v6 on it cannot separate versions; it is kept for comparison with v0 to v5.\n")
    if ev.get("rates"):
        L.append("| Label | TPR | TNR |\n| --- | --- | --- |")
        for l, r in ev["rates"].items():
            L.append(f"| {l} | {r.get('tpr')} | {r.get('tnr')} |")
        L.append("")
    L.append("## The served copy (Cloudflare Workers AI)\n")
    if cf:
        L.append(f"Served by {cf.get('served_by')}: n {cf.get('n')}, label accuracy {pct(cf.get('label_accuracy'))}, JSON valid {pct(cf.get('json_valid'))}, evidence hit {pct(cf.get('evidence_hit'))}." + (f" Errors: {cf.get('errors')}" if cf.get("errors") else "") + "\n")
        if cf.get("label_accuracy") == 0:
            L.append("A served score of zero means the Worker did not answer, not that the model is wrong: see the errors above and run the Zeus served check workflow.\n")
    else:
        L.append("Not measured yet.\n")
    L.append("## How to read this\n")
    L.append("- Train and eval are split by source passage, so the same Wikipedia text never sits on both sides.\n- Contradicted examples are oversampled on purpose; they are rare in natural data.\n- Zeus never trains on its own labels. Flags from Olo's apps become training examples only after a person accepts them (docs/FEEDBACK.md).\n- The next scorecard replaces this file; every version's raw files stay under zeus/out/.\n")
    os.makedirs(DOCS, exist_ok=True)
    path = os.path.join(DOCS, "ZEUS_SCORECARD.md")
    open(path, "w", encoding="utf-8").write("\n".join(L))
    print(f"wrote {path} for {v}")


if __name__ == "__main__":
    main()
